function SpecialUpgrades:RegisterEventListeners()
	if self.abilityUsedListener then return end
	self.abilityUsedListener = ListenToGameEvent("dota_player_used_ability", function(keys)
		self:OnAbilityUsed(keys)
	end, nil)
	self:DebugLog("Registered dota_player_used_ability listener=" .. tostring(self.abilityUsedListener))
end

function SpecialUpgrades:IsDraftAbilitySlotValid(abilitySlot)
	if abilitySlot == "ultimate" then return true end
	if type(abilitySlot) == "string" and string.find(abilitySlot, "^base_") then
		return true
	end
	return false
end

function SpecialUpgrades:HasAbilityUpgradeData(abilityName)
	for _, heroUpgrades in pairs(_G.MINOR_ABILITY_UPGRADES or {}) do
		if type(heroUpgrades) == "table" then
			for _, upgrade in pairs(heroUpgrades) do
				if upgrade and upgrade.ability_name == abilityName then
					return true
				end
			end
		end
	end

	return false
end

function SpecialUpgrades:IsValidSpecialUpgradeTargetAbility(abilityName)
	if not abilityName or abilityName == "" then return false end
	if abilityName == "generic_hidden" then return false end
	if self.blocked_ability_names[abilityName] then return false end
	if string.find(abilityName, "special_bonus") then return false end
	if string.find(abilityName, "^generic_") then return false end
	return self:HasAbilityUpgradeData(abilityName)
end

function SpecialUpgrades:GetDraftPickedAbilityNames(hero)
	local result = {}
	if not hero or not hero.GetPlayerOwnerID then return result end

	local playerID = hero:GetPlayerOwnerID()
	local abilityDraftMode = GameRules.holdOut and GameRules.holdOut.abilityDraftMode
	local playersPickedAbilities = abilityDraftMode and abilityDraftMode.playersPickedAbilities
	local pickedAbilities = playersPickedAbilities and playersPickedAbilities[playerID]

	if type(pickedAbilities) ~= "table" then
		return result
	end

	for _, abilityData in pairs(pickedAbilities) do
		local abilityName = abilityData and abilityData.ability_name
		local abilitySlot = abilityData and abilityData.ability_slot
		if self:IsDraftAbilitySlotValid(abilitySlot) and self:IsValidSpecialUpgradeTargetAbility(abilityName) then
			result[abilityName] = true
		end
	end

	return result
end

function SpecialUpgrades:GetEntityAbilityNames(hero)
	local result = {}
	if not hero or not hero.GetAbilityCount then return result end

	for i = 0, hero:GetAbilityCount() - 1, 1 do
		local ability = hero:GetAbilityByIndex(i)
		if ability and not ability:IsNull() and not ability:IsAttributeBonus() then
			local abilityName = ability:GetAbilityName()
			if self:IsValidSpecialUpgradeTargetAbility(abilityName) then
				result[abilityName] = true
			end
		end
	end

	return result
end

function SpecialUpgrades:GetHeroAbilityNames(hero)
	if self:IsEnabledForCurrentMap() then
		return self:GetDraftPickedAbilityNames(hero)
	end

	return self:GetEntityAbilityNames(hero)
end

function SpecialUpgrades:HasUpgrade(hero, abilityName, upgradeName)
	local picked = hero and hero.SpecialUpgrades
	return picked and picked[abilityName] and picked[abilityName][upgradeName] == 1
end

function SpecialUpgrades:GetAbilityBehaviorString(abilityName)
	if not GetAbilityKeyValuesByName then return "" end
	local kv = GetAbilityKeyValuesByName(abilityName)
	return kv and kv.AbilityBehavior and tostring(kv.AbilityBehavior) or ""
end

function SpecialUpgrades:IsAbilityBlockedForUpgrade(abilityName, data)
	if self.blocked_generic_upgrade_targets[abilityName] and not data.target_abilities then
		return true
	end

	local excludedBehaviors = data and data.excluded_behaviors
	if not excludedBehaviors then return false end

	local behavior = self:GetAbilityBehaviorString(abilityName)
	for behaviorName, blocked in pairs(excludedBehaviors) do
		if blocked and string.find(behavior, behaviorName, 1, true) then
			return true
		end
	end

	return false
end

function SpecialUpgrades:ApplyArcaneSurgeFromAbilityUsed(hero, abilityName)
	if not hero or not abilityName or abilityName == "" then return false end
	if not self:HasUpgrade(hero, abilityName, "arcane_surge") then return false end

	local data = SPECIAL_UPGRADES and SPECIAL_UPGRADES.data and SPECIAL_UPGRADES.data.arcane_surge
	if not data then return false end

	local targetAbility = hero:FindAbilityByName(abilityName)
	local values = data.values or {}
	local duration = tonumber(values.duration) or 4
	local spellAmp = tonumber(values.spell_amp) or 35
	local buff = hero:AddNewModifier(hero, targetAbility, "modifier_special_upgrade_arcane_surge_buff", {
		duration = duration,
		spell_amp = spellAmp,
	})

	self:DebugLog("ArcaneSurge global fallback ability=" .. tostring(abilityName)
		.. " hero=" .. tostring(hero.GetUnitName and hero:GetUnitName())
		.. " buff_created=" .. tostring(buff ~= nil)
		.. " duration=" .. tostring(duration)
		.. " spell_amp=" .. tostring(spellAmp))

	return buff ~= nil
end

function SpecialUpgrades:OnAbilityUsed(keys)
	local abilityName = keys and keys.abilityname
	local caster = keys and keys.caster_entindex and EntIndexToHScript(keys.caster_entindex) or nil
	if not caster or caster:IsNull() then
		local playerID = keys and keys.PlayerID
		caster = playerID and PlayerResource:GetSelectedHeroEntity(playerID) or nil
	end

	if not caster or caster:IsNull() then return end
	self:DebugLog("OnAbilityUsed player=" .. tostring(keys and keys.PlayerID)
		.. " hero=" .. tostring(caster.GetUnitName and caster:GetUnitName())
		.. " ability=" .. tostring(abilityName))

	self:ApplyArcaneSurgeFromAbilityUsed(caster, abilityName)
end

function SpecialUpgrades:IsUpgradeValidForAbility(upgradeName, abilityName)
	local data = SPECIAL_UPGRADES and SPECIAL_UPGRADES.data and SPECIAL_UPGRADES.data[upgradeName]
	if not data then return false end
	if self:IsAbilityBlockedForUpgrade(abilityName, data) then return false end
	if not data.target_abilities then return true end
	return data.target_abilities[abilityName] == true
end

function SpecialUpgrades:GetBaseHeroAbilityNames(heroName)
	local result = {}
	if not heroName or not DOTAGameManager or not DOTAGameManager.GetHeroDataByName_Script then
		return result
	end

	local heroData = DOTAGameManager:GetHeroDataByName_Script(heroName)
	if type(heroData) ~= "table" then return result end

	for key, abilityName in pairs(heroData) do
		if type(key) == "string" and string.find(key, "^Ability") and type(abilityName) == "string" and abilityName ~= "" then
			result[abilityName] = true
		end
	end

	return result
end

function SpecialUpgrades:GetSpecialUpgradesDescription(heroName, abilityName)
	local heroAbilities = heroName and self:GetBaseHeroAbilityNames(heroName) or nil
	local result = {}

	for _, upgradeName in ipairs(SPECIAL_UPGRADES.order or {}) do
		local data = SPECIAL_UPGRADES.data and SPECIAL_UPGRADES.data[upgradeName]
		if data and data.target_abilities then
			for targetAbilityName, enabled in pairs(data.target_abilities) do
				if enabled
					and (not abilityName or abilityName == targetAbilityName)
					and (not heroAbilities or heroAbilities[targetAbilityName]) then
					result[targetAbilityName] = result[targetAbilityName] or {}
					table.insert(result[targetAbilityName], {
						upgrade_name = upgradeName,
						ability_name = data.ability_name,
						description = data.description,
						value_text = data.value_text,
					})
				end
			end
		end
	end

	return result
end

function SpecialUpgrades:IsAnySpecialUpgradeAvailable(heroName)
	local upgrades = self:GetSpecialUpgradesDescription(heroName)
	for _, abilityUpgrades in pairs(upgrades) do
		if type(abilityUpgrades) == "table" and #abilityUpgrades > 0 then
			return true
		end
	end

	return false
end

function SpecialUpgrades:BuildReward(hero, abilityName, upgradeName)
	local data = SPECIAL_UPGRADES and SPECIAL_UPGRADES.data and SPECIAL_UPGRADES.data[upgradeName]
	if not data then return nil end

	local reward = {}
	for k, v in pairs(data) do
		if k ~= "values" then reward[k] = v end
	end

	reward.is_special_upgrade = 1
	reward.special_upgrade = 1
	reward.reward_level = "special_upgrade"
	reward.ability_parent_name = abilityName
	reward.target_ability_name = abilityName
	reward.upgraded_ability = abilityName
	reward.special_upgrade_name = upgradeName

	return reward
end

function SpecialUpgrades:PickReward(hero)
	if not self:IsEnabledForCurrentMap() then return nil end
	if not hero then return nil end

	local abilities = self:GetHeroAbilityNames(hero)
	local candidates = {}

	for abilityName, _ in pairs(abilities) do
		for _, upgradeName in ipairs(SPECIAL_UPGRADES.order or {}) do
			if self:IsUpgradeValidForAbility(upgradeName, abilityName) and not self:HasUpgrade(hero, abilityName, upgradeName) then
				table.insert(candidates, { ability_name = abilityName, upgrade_name = upgradeName })
			end
		end
	end

	if #candidates == 0 then return nil end

	local selected = candidates[RandomInt(1, #candidates)]
	return self:BuildReward(hero, selected.ability_name, selected.upgrade_name)
end

function SpecialUpgrades:Apply(hero, reward)
	if not hero or not reward or reward.is_special_upgrade ~= 1 then
		return false
	end

	local abilityName = reward.ability_parent_name or reward.target_ability_name or reward.upgraded_ability
	local upgradeName = reward.special_upgrade_name or reward.upgrade_name
	local data = SPECIAL_UPGRADES and SPECIAL_UPGRADES.data and SPECIAL_UPGRADES.data[upgradeName]
	local playerID = hero.GetPlayerOwnerID and hero:GetPlayerOwnerID() or -1
	self:DebugLog("Apply requested player=" .. tostring(playerID)
		.. " hero=" .. tostring(hero.GetUnitName and hero:GetUnitName())
		.. " upgrade=" .. tostring(upgradeName)
		.. " target=" .. tostring(abilityName)
		.. " modifier=" .. tostring(data and data.modifier_name))
	if not abilityName or not upgradeName or not data then
		self:DebugLog("Apply rejected: missing abilityName/upgradeName/data")
		return false
	end

	local targetAbility = hero:FindAbilityByName(abilityName)
	if not targetAbility then
		self:DebugLog("Apply rejected: missing target ability " .. tostring(abilityName))
		return false
	end

	hero.SpecialUpgrades = hero.SpecialUpgrades or {}
	hero.SpecialUpgrades[abilityName] = hero.SpecialUpgrades[abilityName] or {}
	if hero.SpecialUpgrades[abilityName][upgradeName] == 1 then
		self:DebugLog("Apply skipped: already has upgrade=" .. tostring(upgradeName) .. " target=" .. tostring(abilityName))
		return true
	end

	self:LinkModifier(upgradeName)

	local kv = {
		upgraded_ability = abilityName,
		special_upgrade_name = upgradeName,
	}
	for key, value in pairs(data.values or {}) do
		kv[key] = value
	end

	local modifier = hero:AddNewModifier(hero, targetAbility, data.modifier_name, kv)
	self:DebugLog("AddNewModifier result upgrade=" .. tostring(upgradeName)
		.. " target=" .. tostring(abilityName)
		.. " modifier=" .. tostring(data.modifier_name)
		.. " created=" .. tostring(modifier ~= nil)
		.. " targetAbilityLevel=" .. tostring(targetAbility.GetLevel and targetAbility:GetLevel()))
	if modifier and modifier.InitializeSpecialUpgrade then
		modifier:InitializeSpecialUpgrade(abilityName, upgradeName, data.values or {})
		self:DebugLog("InitializeSpecialUpgrade called upgrade=" .. tostring(upgradeName) .. " target=" .. tostring(abilityName))
	elseif modifier then
		self:DebugLog("InitializeSpecialUpgrade missing on modifier=" .. tostring(data.modifier_name))
	end
	hero.SpecialUpgrades[abilityName][upgradeName] = 1

	CustomNetTables:SetTableValue("special_upgrades", tostring(hero:GetPlayerOwnerID()), hero.SpecialUpgrades)
	self:DebugLog("NetTable updated table=special_upgrades player=" .. tostring(playerID))
	return true
end

