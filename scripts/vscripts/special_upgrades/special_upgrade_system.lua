function SpecialUpgrades:Precache(context)
	if not context or not PrecacheResource then return end
	for _, particle in ipairs(self.precache_particles or {}) do
		PrecacheResource("particle", particle, context)
	end
end

function SpecialUpgrades:IsEnabledForCurrentMap()
	return GetMapName and GetMapName() == "epic_boss_fight_ad"
end

function SpecialUpgrades:LinkModifier(upgradeName)
	local data = SPECIAL_UPGRADES and SPECIAL_UPGRADES.data and SPECIAL_UPGRADES.data[upgradeName]
	local path = self.modifier_paths[upgradeName]
	if not path and data and data.modifier_name then
		path = "modifiers/special_upgrades/" .. data.modifier_name
	end
	if not path then return end

	if data and data.modifier_name then
		LinkLuaModifier(data.modifier_name, path, LUA_MODIFIER_MOTION_NONE)
	end

	for _, modifierName in ipairs((data and data.extra_modifiers) or {}) do
		LinkLuaModifier(modifierName, "modifiers/special_upgrades/" .. modifierName, LUA_MODIFIER_MOTION_NONE)
	end

	if upgradeName == "arcane_surge" then
		LinkLuaModifier("modifier_special_upgrade_arcane_surge_buff", path, LUA_MODIFIER_MOTION_NONE)
	end
end

function SpecialUpgrades:GetHeroByPlayerID(playerID)
	if playerID == nil then return nil end
	if PlayerResource and PlayerResource.GetSelectedHeroEntity then
		return PlayerResource:GetSelectedHeroEntity(playerID)
	end
	return nil
end

function SpecialUpgrades:GetUpgradeByDarkmoonName(abilityName, darkmoonUpgradeName)
	for upgradeName, data in pairs(SPECIAL_UPGRADES.data or {}) do
		if data.darkmoon_name == darkmoonUpgradeName and data.target_abilities and data.target_abilities[abilityName] then
			return upgradeName, data
		end
	end
	return nil, nil
end

function _HasPlayerChosenSpecialUpgrade(playerID, abilityName, darkmoonUpgradeName)
	local upgradeName = SpecialUpgrades:GetUpgradeByDarkmoonName(abilityName, darkmoonUpgradeName)
	if not upgradeName then return false end
	local hero = SpecialUpgrades:GetHeroByPlayerID(playerID)
	return SpecialUpgrades:HasUpgrade(hero, abilityName, upgradeName)
end

function _G._GetSpecialUpgradeValues(heroName, abilityName, darkmoonUpgradeName)
	local _, data = SpecialUpgrades:GetUpgradeByDarkmoonName(abilityName, darkmoonUpgradeName)
	return data and data.values or nil
end

